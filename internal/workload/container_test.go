func TestPinnedCLIDefaults(t *testing.T) {
	const request = `{"location":"farm-1","tags":{},"properties":{"osType":"Linux","restartPolicy":"Always",` +
		`"ipAddress":{"ports":[{"protocol":"TCP","port":80}],"type":"Public","autoGeneratedDomainNameLabelScope":"Unsecure"},` +
		`"containers":[{"name":"fixture","properties":{"image":"docker.io/library/nginx@sha256:` +
		`836c5af5a07dbff704e8ba7971d20dd55bc96d5748a03129f02bd4ce25836e0d","ports":[{"protocol":"TCP","port":80}],` +
		`"configMap":{"keyValuePairs":{}},"resources":{"requests":{"memoryInGB":0.0625,"cpu":0.25}}}}]}}`
	var group ContainerGroup
	decoder := json.NewDecoder(strings.NewReader(request))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(&group); err != nil || group.Validate("fixture") != nil {
		t.Fatalf("CLI defaults were rejected: %v", err)
	}
	cpu, memory, ok := group.Properties.Containers[0].Properties.Resources.Requests.Limits()
	if !ok || cpu != 250 || memory != 64 || group.Properties.IPAddress.AutoGeneratedDomainNameLabelScope != "" ||
		group.Properties.Containers[0].Properties.ConfigMap != nil {
		t.Fatal("CLI request did not reduce to the admitted configuration")
	}
	group.Properties.Containers[0].Properties.ConfigMap = &EmptyConfigMap{KeyValuePairs: map[string]string{"unsupported": "setting"}}
	if group.Validate("fixture") == nil {
		t.Fatal("the CLI default exception allowed a populated config map")
	}
}

func TestRedactLogsOverlappingValues(t *testing.T) {
	short, long := "test-secret", "test-secret-long-suffix"
	vars := []Variable{{Name: "SHORT", SecureValue: &short}, {Name: "LONG", SecureValue: &long}}
	redacted := RedactLogs("start "+long+" "+short, vars)
	if redacted != "start [redacted] [redacted]" {
		t.Fatalf("unexpected redaction: %q", redacted)
	}
}
