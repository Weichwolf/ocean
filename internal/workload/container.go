// Package workload defines the admitted Linux container configuration.
package workload

import (
	"errors"
	"math"
	"regexp"
	"slices"
	"strings"

	"github.com/Weichwolf/ocean/internal/storage"
)

const (
	ContainerGroupType       = "Microsoft.ContainerInstance/containerGroups"
	ContainerGroupAPIVersion = "2024-05-01-preview"
)

var (
	ErrInvalidContainer = errors.New("the container group configuration is unsupported")
	groupName           = regexp.MustCompile(`^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$`)
	variableName        = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]{0,127}$`)
	publicImage         = regexp.MustCompile(`^(docker\.io|mcr\.microsoft\.com|ghcr\.io|quay\.io)/[a-z0-9][a-z0-9._/-]*@sha256:[a-f0-9]{64}$`)
)

type ContainerGroup struct {
	Location   string                   `json:"location"`
	Tags       map[string]string        `json:"tags,omitempty"`
	Properties ContainerGroupProperties `json:"properties"`
}

type ContainerGroupProperties struct {
	Containers    []Container `json:"containers"`
	OSType        string      `json:"osType"`
	RestartPolicy string      `json:"restartPolicy"`
	IPAddress     *Endpoint   `json:"ipAddress,omitempty"`
	SubnetIDs     []Subnet    `json:"subnetIds,omitempty"`
	SKU           string      `json:"sku,omitempty"`
	Priority      string      `json:"priority,omitempty"`
	Volumes       []Volume    `json:"volumes,omitempty"`
}

type Container struct {
	Name       string              `json:"name"`
	Properties ContainerProperties `json:"properties"`
}

type ContainerProperties struct {
	Image                string               `json:"image"`
	Command              []string             `json:"command,omitempty"`
	Ports                []Port               `json:"ports,omitempty"`
	EnvironmentVariables []Variable           `json:"environmentVariables,omitempty"`
	Resources            ResourceRequirements `json:"resources"`
	VolumeMounts         []VolumeMount        `json:"volumeMounts,omitempty"`
	ConfigMap            *EmptyConfigMap      `json:"configMap,omitempty"`
}

type Volume struct {
	Name      string           `json:"name"`
	AzureFile *AzureFileVolume `json:"azureFile"`
}

type AzureFileVolume struct {
	ShareName          string `json:"shareName"`
	StorageAccountName string `json:"storageAccountName"`
	StorageAccountKey  string `json:"storageAccountKey,omitempty"`
	ReadOnly           bool   `json:"readOnly,omitempty"`
}

type VolumeMount struct {
	Name      string `json:"name"`
	MountPath string `json:"mountPath"`
	ReadOnly  bool   `json:"readOnly,omitempty"`
}

func validMount(volumes []Volume, mounts []VolumeMount) bool {
	if len(volumes) == 0 && len(mounts) == 0 {
		return true
	}
	if len(volumes) != 1 || len(mounts) != 1 {
		return false
	}
	volume, mount := volumes[0], mounts[0]
	share := volume.AzureFile
	return ValidName(volume.Name) && volume.Name == mount.Name && mount.MountPath == "/data" && !mount.ReadOnly &&
		share != nil && !share.ReadOnly && storage.ValidAccount(share.StorageAccountName) && storage.ValidShare(share.ShareName) &&
		len(share.StorageAccountKey) == 88
}

type EmptyConfigMap struct {
	KeyValuePairs map[string]string `json:"keyValuePairs"`
}

type ResourceRequirements struct {
	Requests ResourceAmounts `json:"requests"`
}

type ResourceAmounts struct {
	CPU        float64 `json:"cpu"`
	MemoryInGB float64 `json:"memoryInGB"`
}

type Port struct {
	Port     int    `json:"port"`
	Protocol string `json:"protocol"`
}

type Endpoint struct {
	Type                              string `json:"type"`
	Ports                             []Port `json:"ports"`
	AutoGeneratedDomainNameLabelScope string `json:"autoGeneratedDomainNameLabelScope,omitempty"`
}

type Subnet struct {
	ID string `json:"id"`
}

type Variable struct {
	Name        string  `json:"name"`
	Value       *string `json:"value,omitempty"`
	SecureValue *string `json:"secureValue,omitempty"`
}

func ValidName(name string) bool {
	return groupName.MatchString(name) && !strings.Contains(name, "--")
}

func (r ResourceAmounts) Limits() (cpuMillis, memoryMiB int64, valid bool) {
	millis := r.CPU * 1000
	memory := math.Ceil(r.MemoryInGB * 1024)
	if millis < 10 || millis > 16000 || math.Abs(millis-math.Round(millis)) > 1e-8 || memory < 16 || memory > 32768 {
		return 0, 0, false
	}
	return int64(math.Round(millis)), int64(memory), true
}

// Validate requires one Linux container with one TCP endpoint. For this
// contract the same CPU and memory limits apply to placement and execution.
func (g *ContainerGroup) Validate(name string) error {
	p := &g.Properties
	if !ValidName(name) || len(p.Containers) != 1 || p.Containers[0].Name != name || p.OSType != "Linux" ||
		!slices.Contains([]string{"Always", "Never", "OnFailure"}, p.RestartPolicy) ||
		p.SKU != "" && p.SKU != "Standard" || p.Priority != "" && p.Priority != "Regular" {
		return ErrInvalidContainer
	}
	c := &p.Containers[0].Properties
	if len(c.Image) > 384 || !publicImage.MatchString(c.Image) || strings.Contains(c.Image, "//") || len(c.Command) > 32 ||
		len(c.EnvironmentVariables) > 32 || c.ConfigMap != nil && len(c.ConfigMap.KeyValuePairs) != 0 ||
		!validMount(p.Volumes, c.VolumeMounts) {
		return ErrInvalidContainer
	}
	if _, _, ok := c.Resources.Requests.Limits(); !ok {
		return ErrInvalidContainer
	}
	for _, value := range c.Command {
		if len(value) > 4096 || strings.IndexByte(value, 0) >= 0 {
			return ErrInvalidContainer
		}
	}
	seen := make(map[string]bool)
	for _, variable := range c.EnvironmentVariables {
		if !variable.Valid() || seen[variable.Name] {
			return ErrInvalidContainer
		}
		seen[variable.Name] = true
	}
	if len(g.Tags) == 0 {
		g.Tags = nil
	}
	c.ConfigMap = nil
	p.SKU, p.Priority = "Standard", "Regular"
	if p.IPAddress == nil || len(p.IPAddress.Ports) != 1 || len(c.Ports) != 1 ||
		p.IPAddress.AutoGeneratedDomainNameLabelScope != "" && p.IPAddress.AutoGeneratedDomainNameLabelScope != "Unsecure" {
		return ErrInvalidContainer
	}
	p.IPAddress.AutoGeneratedDomainNameLabelScope = ""
	port := &p.IPAddress.Ports[0]
	if !strings.EqualFold(port.Protocol, "TCP") || !strings.EqualFold(c.Ports[0].Protocol, "TCP") ||
		port.Port != c.Ports[0].Port || port.Port < 1 || port.Port > 65535 {
		return ErrInvalidContainer
	}
	port.Protocol, c.Ports[0].Protocol = "TCP", "TCP"
	switch p.IPAddress.Type {
	case "Public":
		if len(p.SubnetIDs) == 0 {
			return nil
		}
	case "Private":
		if len(p.SubnetIDs) == 1 && p.SubnetIDs[0].ID != "" {
			return nil
		}
	}
	return ErrInvalidContainer
}

func (v Variable) Valid() bool {
	if !variableName.MatchString(v.Name) || (v.Value == nil) == (v.SecureValue == nil) {
		return false
	}
	value := v.Text()
	return len(value) <= 2048 && !strings.ContainsAny(value, "\x00\r\n") && (v.SecureValue == nil || value != "")
}

func (v Variable) Text() string {
	if v.Value != nil {
		return *v.Value
	}
	if v.SecureValue != nil {
		return *v.SecureValue
	}
	return ""
}
